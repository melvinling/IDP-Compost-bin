"""Bundle editable offline website sources. Python standard library only."""
import argparse
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
def bundle():
    blocks = ["// Generated by tools/bundle_web.py; edit web/ sources, then regenerate.\n#pragma once\n#include <Arduino.h>\n"]
    for name, filename in (("WEB_INDEX", "index.html"), ("WEB_STYLE", "style.css"), ("WEB_APP", "app.js")):
        source = (ROOT / "web" / filename).read_text(encoding="utf-8")
        delimiter = "COMPOST_ASSET"
        if ")" + delimiter + '"' in source:
            raise ValueError("Raw-string delimiter collision in " + filename)
        blocks.append(f'const char {name}[] PROGMEM = R"{delimiter}({source}){delimiter}";\n')
    return "\n".join(blocks)
if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="Verify checked-in header matches sources")
    args = parser.parse_args()
    target = ROOT / "src" / "WebAssets.h"
    content = bundle()
    if args.check:
        if not target.exists() or target.read_text(encoding="utf-8") != content:
            raise SystemExit("WebAssets.h is stale; run python tools/bundle_web.py")
        print("Web assets match sources")
    else:
        target.write_text(content, encoding="utf-8")
        print("Generated src/WebAssets.h")
