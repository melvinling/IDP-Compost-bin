"""Train/export the SYNTHETIC demonstration model; no real-world performance claim."""
import csv
import hashlib
import json
from pathlib import Path

import numpy as np
import sklearn
from sklearn.ensemble import RandomForestClassifier
from sklearn.metrics import accuracy_score, confusion_matrix, f1_score
from sklearn.model_selection import GroupShuffleSplit
from sklearn.tree import DecisionTreeClassifier

ROOT = Path(__file__).resolve().parents[1]
FEATURES = ['moisture_pct', 'temperature_c', 'ec_us_cm', 'ph', 'co2_ppm', 'distance_cm',
            'process_stage', 'periodic_mix_due', 'post_watering_mix_due']
CLASSES = ['idle', 'water', 'dry', 'mix']


def inputs(row):
    return [float(row[k]) if k != 'process_stage' else float(row[k] == 'finishing') for k in FEATURES]


def policy(x):
    moisture, *_, stage, periodic, post = x
    return 0 if not stage else 3 if post else 1 if moisture < 40 else 2 if moisture > 60 else 3 if periodic else 0


def main():
    dataset = ROOT / 'data/bokashi_dummy_training.csv'
    rows = list(csv.DictReader(dataset.open(encoding='utf-8-sig')))
    assert len(rows) == 1200 and all(r['data_source'] == 'synthetic_demo' for r in rows)
    x = np.asarray([inputs(r) for r in rows], dtype=np.float32)
    y = np.asarray([CLASSES.index(r['target_action']) for r in rows])
    assert np.array_equal(y, [policy(r) for r in x])
    groups = [r['scenario_group_id'] for r in rows]
    train, test = next(GroupShuffleSplit(n_splits=1, test_size=.25, random_state=42).split(x, y, groups))
    forest = RandomForestClassifier(n_estimators=32, max_depth=6, random_state=42, n_jobs=1)
    tree = DecisionTreeClassifier(max_depth=6, random_state=42)
    forest.fit(x[train], y[train]); tree.fit(x[train], y[train])
    metrics = {}
    for name, predicted in [('random_forest', forest.predict(x[test])), ('decision_tree', tree.predict(x[test])),
                            ('label_rule', np.asarray([policy(r) for r in x[test]]))]:
        metrics[name] = dict(accuracy=float(accuracy_score(y[test], predicted)),
                             macro_f1=float(f1_score(y[test], predicted, labels=range(4), zero_division=0, average='macro')),
                             confusion_matrix=confusion_matrix(y[test], predicted, labels=range(4)).tolist())
    # Deploy the evaluated forest, without retraining on its holdout.
    nodes, roots = [], []
    for estimator in forest.estimators_:
        t = estimator.tree_; offset = len(nodes); roots.append(offset)
        for i in range(t.node_count):
            prob = t.value[i][0]; prob = prob / prob.sum()
            nodes.append((int(t.feature[i]), float(t.threshold[i]),
                          int(t.children_left[i] + offset) if t.children_left[i] >= 0 else 0,
                          int(t.children_right[i] + offset) if t.children_right[i] >= 0 else 0, prob.tolist()))
    # Keep thresholds as doubles, matching sklearn's float32 inputs compared to double splits.
    header = ['// Generated by ml/train.py from synthetic data. Do not edit.', '#pragma once', '#include <stdint.h>',
              'namespace Forest {', 'struct Node { int8_t feature; double threshold; uint16_t left, right; float probabilities[4]; };',
              'constexpr unsigned TREE_COUNT = 32;', 'constexpr uint16_t roots[] = {' + ','.join(map(str, roots)) + '};',
              'constexpr Node nodes[] = {']
    for feature, threshold, left, right, prob in nodes:
        header.append('{%d,%.17g,%d,%d,{%s}},' % (feature, threshold, left, right, ','.join(f'{p:.9g}f' if '.' in f'{p:.9g}' or 'e' in f'{p:.9g}' else f'{p:.9g}.0f' for p in prob)))
    header += ['};', '}']
    (ROOT / 'src/GeneratedForest.h').write_text('\n'.join(header) + '\n', encoding='utf-8')
    report = dict(provenance='synthetic_demo', warning='Scores measure imitation of artificial labels; not real compost performance.',
                  dataset_sha256=hashlib.sha256(dataset.read_bytes()).hexdigest(), sklearn_version=sklearn.__version__,
                  seed=42, features=FEATURES, classes=CLASSES, stage_encoding=dict(fermentation=0, finishing=1),
                  parameters=forest.get_params(), train_rows=len(train), test_rows=len(test),
                  train_groups=sorted(set(groups[i] for i in train)), test_groups=sorted(set(groups[i] for i in test)),
                  metrics=metrics, nodes=len(nodes), feature_importances=forest.feature_importances_.tolist())
    (ROOT / 'ml/report.json').write_text(json.dumps(report, indent=2) + '\n', encoding='utf-8')
    # Parity set contains all data, broad random probes and threshold neighbours.
    rng = np.random.default_rng(42)
    probes = rng.uniform([0,-40,0,0,0,3,0,0,0], [100,80,10000,14,10000,450,1,1,1], (1000,9)).astype(np.float32)
    probes[:,6:] = rng.integers(0,2,(1000,3))
    neighbours = []
    for feature, threshold, *_ in nodes:
        if feature < 0: continue
        for value in [np.nextafter(np.float32(threshold), np.float32(-np.inf)), np.float32(threshold),
                      np.nextafter(np.float32(threshold), np.float32(np.inf))]:
            row = x[0].copy(); row[feature] = value; neighbours.append(row)
    probes = np.vstack([x, probes, neighbours])
    with (ROOT / 'ml/parity.csv').open('w', newline='', encoding='utf-8') as f:
        writer = csv.writer(f); writer.writerow(FEATURES + ['p_idle','p_water','p_dry','p_mix'])
        for row, prob in zip(probes, forest.predict_proba(probes)): writer.writerow([*map(float,row), *map(float,prob)])
    print(json.dumps(dict(nodes=len(nodes), parity_cases=len(probes), metrics=metrics), indent=2))


if __name__ == '__main__': main()
